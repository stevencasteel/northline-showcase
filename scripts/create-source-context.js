import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const outputPath = path.join(
  rootDir,
  "docs",
  "northline-roofing_source_code.txt",
);

const includedRoots = ["src", "public", "docs", "scripts", "tests", ".github"];
const includedRootFiles = [
  "README.md",
  "DESIGN.md",
  "package.json",
  "package-lock.json",
  "tsconfig.json",
  "tsconfig.app.json",
  "tsconfig.node.json",
  "vite.config.ts",
  "eslint.config.js",
  "postcss.config.js",
  "tailwind.config.js",
  "wrangler.jsonc",
  "index.html",
  "playwright.config.ts",
  ".gitignore",
];

const ignoredDirectories = new Set([
  ".git",
  ".cache",
  ".wrangler",
  "dist",
  "node_modules",
  "coverage",
  "test-results",
  "playwright-report",
  "playwright-browsers",
]);

const ignoredNames = new Set([
  ".DS_Store",
  "bundle-report.json",
  "northline-roofing_source_code.txt",
  "worker-configuration.d.ts",
]);

const textExtensions = new Set([
  ".cjs",
  ".css",
  ".d.ts",
  ".html",
  ".js",
  ".json",
  ".jsx",
  ".md",
  ".mjs",
  ".ts",
  ".tsx",
  ".txt",
  ".xml",
  ".yaml",
  ".yml",
  ".webmanifest",
  ".jsonc",
]);

const ignoredExtensions = new Set([
  ".avif",
  ".bmp",
  ".gif",
  ".ico",
  ".jpeg",
  ".jpg",
  ".mp3",
  ".mp4",
  ".ogg",
  ".otf",
  ".pdf",
  ".png",
  ".svg",
  ".wav",
  ".webp",
  ".woff",
  ".woff2",
]);

async function exists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function isTextFile(relativePath) {
  const extension = path.extname(relativePath).toLowerCase();
  return !ignoredExtensions.has(extension) && textExtensions.has(extension);
}

async function collectFiles(relativeDirectory) {
  const absoluteDirectory = path.join(rootDir, relativeDirectory);
  if (!(await exists(absoluteDirectory))) return [];

  const entries = await fs.readdir(absoluteDirectory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (ignoredNames.has(entry.name)) continue;
    const relativePath = path.join(relativeDirectory, entry.name);

    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name)) {
        files.push(...(await collectFiles(relativePath)));
      }
      continue;
    }

    if (entry.isFile() && isTextFile(relativePath)) files.push(relativePath);
  }

  return files;
}

async function collectSourceFiles() {
  const rootFiles = [];
  for (const file of includedRootFiles) {
    if (await exists(path.join(rootDir, file))) rootFiles.push(file);
  }

  const nestedFiles = [];
  for (const directory of includedRoots) {
    nestedFiles.push(...(await collectFiles(directory)));
  }

  return [...new Set([...rootFiles, ...nestedFiles])].sort((a, b) =>
    a.localeCompare(b),
  );
}

function renderTree(files) {
  return files.map((file) => `  ${file}`).join("\n");
}

async function renderFile(relativePath) {
  const absolutePath = path.join(rootDir, relativePath);
  const contents = await fs.readFile(absolutePath, "utf8");
  return [
    `===== ${relativePath} =====`,
    contents.trimEnd(),
    `===== END ${relativePath} =====`,
  ].join("\n");
}

const files = await collectSourceFiles();
const generatedAt = new Date().toISOString();
const sections = [];

sections.push(
  [
    "NORTHLINE ROOFING SOURCE CONTEXT",
    `Generated: ${generatedAt}`,
    `Project root: ${rootDir}`,
    `Included files: ${files.length}`,
    "",
    "This file is generated by scripts/create-source-context.js.",
    "It contains the readable project source, configuration, and documentation needed to understand the site.",
    "Binary assets, generated output, dependencies, and caches are intentionally omitted.",
    "",
    "PROJECT FILES",
    renderTree(files),
  ].join("\n"),
);

for (const file of files) sections.push(await renderFile(file));

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, `${sections.join("\n\n")}\n`, "utf8");

console.log(`Source context written to ${path.relative(rootDir, outputPath)}`);
console.log(`Included ${files.length} readable project files.`);
